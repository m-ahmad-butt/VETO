"""Create deterministic local development ZIPs. Does NOT execute fixture PHP."""

import hashlib
import json
from pathlib import Path
import stat
import zipfile

BASE = Path(__file__).resolve().parents[1]


def build(destination=None):
    destination = Path(destination) if destination else BASE / "fixtures" / "generated"
    destination.mkdir(parents=True, exist_ok=True)
    sources = BASE / "fixtures" / "sources"
    benign = (sources / "benign.php.txt").read_bytes().replace(b"\r\n", b"\n")
    suspicious = (sources / "suspicious.php.txt").read_bytes().replace(b"\r\n", b"\n")
    capabilities = (sources / "capabilities.php.txt").read_bytes().replace(b"\r\n", b"\n")
    cases = {
        "benign": [("benign/benign.php", benign)],
        "capabilities": [("capabilities/main.php", capabilities)],
        "suspicious": [("suspicious/main.php", suspicious)],
        "missing_header": [("example/readme.txt", b"Not a WordPress plugin")],
        "disguised_php": [("example/main.php", benign), ("example/image.jpg", b"<?php eval($_POST['x']);")],
        "nested_archive": [("example/main.php", benign), ("example/assets.zip", b"opaque archive fixture")],
        "traversal": [("../escaped.php", benign)],
        "case_collision": [("example/Main.php", benign), ("example/main.php", benign)],
        "path_conflict": [("example", b"file"), ("example/main.php", benign)],
    }
    expected = {
        "benign": ("completed", []),
        "capabilities": ("completed", ["PHP006", "PHP007", "PHP008"]),
        "suspicious": ("completed", ["YARA001", "YARA002", "PHP001", "PHP002", "PHP003", "PHP004", "PHP005", "PHP006", "PHP007", "PHP008"]),
        "missing_header": ("completed", ["PKG005"]),
        "disguised_php": ("completed", ["PKG004", "PHP001", "YARA002"]),
        "nested_archive": ("completed", ["PKG003"]),
        "traversal": ("rejected", []),
        "case_collision": ("rejected", []),
        "path_conflict": ("rejected", []),
    }
    manifest = {"purpose": "DEVELOPMENT fixtures, not an independent final evaluation or real-malware dataset", "cases": []}
    for name, members in cases.items():
        target = destination / f"{name}.zip"
        with zipfile.ZipFile(target, "w", compression=zipfile.ZIP_DEFLATED) as archive:
            for path, content in members:
                info = zipfile.ZipInfo(path, date_time=(2026, 1, 1, 0, 0, 0))
                info.create_system = 3
                info.external_attr = (stat.S_IFREG | 0o600) << 16
                info.compress_type = zipfile.ZIP_DEFLATED
                archive.writestr(info, content)
        status, rules = expected[name]
        manifest["cases"].append({"filename": target.name, "sha256": hashlib.sha256(target.read_bytes()).hexdigest(),
                                  "expected_status": status, "expected_rules": sorted(rules),
                                  "member_hashes": {path: hashlib.sha256(data).hexdigest() for path, data in members}})
    catalog = {"version": "test-only-1.0.0", "entries": [{"sha256": hashlib.sha256(suspicious).hexdigest(),
               "label": "VETO inert development fixture (NOT verified malware)",
               "source": "fixtures/sources/suspicious.php.txt; generated by tools/build_fixtures.py", "severity": "medium"}]}
    (destination / "test_hash_catalog.json").write_text(json.dumps(catalog, indent=2) + "\n", encoding="utf-8")
    (destination / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    return manifest


if __name__ == "__main__":
    result = build()
    print(f"Built {len(result['cases'])} deterministic development ZIPs in fixtures/generated")
